const difficultyCycle = ["easy", "medium", "hard"];

function shuffleOptions(options, seed) {
  const arr = [...options];
  let state = seed >>> 0;
  for (let i = arr.length - 1; i > 0; i--) {
    state = (state * 1664525 + 1013904223) >>> 0;
    const j = state % (i + 1);
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

const questions = [];
for (const [categorySlug, items] of Object.entries(mergedBank)) {
  const seenTexts = new Set();
  const unique = items.filter((it) => {
    if (seenTexts.has(it.text)) return false;
    seenTexts.add(it.text);
    return true;
  });
  unique.forEach((item, index) => {
    const id = `${categorySlug}-${String(index + 1).padStart(3, "0")}`;
    const question = {
      id,
      categorySlug,
      text: item.text,
      answer: item.answer,
      acceptedAnswers: item.acceptedAnswers ?? [],
      type: item.type,
      difficulty: difficultyCycle[index % difficultyCycle.length],
    };
    if (item.type === "mcq") {
      const options = shuffleOptions(item.options, index + categorySlug.length * 31);
      question.options = options;
      question.correctIndex = options.indexOf(item.answer);
    }
    if (item.mediaUrl) {
      question.mediaUrl = item.mediaUrl;
      question.mediaType = "image";
      question.mediaCredit = item.mediaCredit;
    }
    questions.push(question);
  });
}

